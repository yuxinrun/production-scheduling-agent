#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""LISA 案例 · 交付材料对账：文档里写死的总数，自己加得起来吗？

数据来源（全部为项目真实交付材料，数字是人工从表里读出来的）：
  《问题提炼与目标对齐清单（37项）9.17.xlsx》      → 37 项问题的六类分布与 P0 分布
  《黎阳智能排产排产规则提取清单-V1.0.xlsx》        → 68 条规则（ZD-01-2026-R001~R068）
  《黎阳智能排产项目调研现状报告-1.0.docx》          → 七道工序现状、A-01~A-30 问卷结论
  《黎阳智能排产智能体-需求分析与技术栈方案》        → 56 项能力点检、K1~K9、数据规模
  《投产配置清单》/《MCP开发技术方案》              → 约束条数、工具数、Scope

这个脚本不做任何建模，只做一件很无聊但很值钱的事：把上面这些「文档里印着的总数」
按它们声称的构成重算一遍，看哪一条加不起来。加不起来的数字在现场叫「口径」，
在验收会上叫「事故」。
"""

SEP = "=" * 74


def head(t):
    print("\n" + SEP)
    print(t)
    print(SEP)


# ---------------------------------------------------------------- 1 三十七项
head("[1] 37 项调研问题：六类分布、P0 分布、贡献度三分")
# (类别, 名称, 问题数, P0 数) —— 直接抄 xlsx 的分类行
CLS = [
    ("A", "数据基座与主数据治理", 4, 2),
    ("B", "计划模式与排产规则", 6, 3),
    ("C", "资源与约束建模", 8, 0),
    ("D", "执行闭环与异常返工管理", 10, 1),
    ("E", "齐套与跨工序协同", 6, 2),
    ("F", "指标度量与军工合规", 3, 2),
]
n = sum(c[2] for c in CLS)
p0 = sum(c[3] for c in CLS)
print("六类条数 %s → 加总 %d，文档封面写 37 → %s"
      % ([c[2] for c in CLS], n, "一致" if n == 37 else "不一致，差 %d" % (n - 37)))
print("P0 分布  %s → 加总 %d，文档写 P0 十项 → %s；P1 = %d - %d = %d，文档写二十七项 → %s"
      % ([c[3] for c in CLS], p0, "一致" if p0 == 10 else "不一致",
         n, p0, n - p0, "一致" if n - p0 == 27 else "不一致"))
print("P0 占比 = %d / %d = %.1f%%" % (p0, n, p0 / n * 100))
# xlsx 附表 1「对智能体达成的贡献度」三分
CONTRIB = {"核心贡献": 12, "重要支撑": 15, "外围关联": 10}
print("贡献度三分 %s → 加总 %d → %s"
      % (list(CONTRIB.values()), sum(CONTRIB.values()),
         "一致" if sum(CONTRIB.values()) == 37 else "不一致"))
print("  注：这份 xlsx 自己在修订说明里写着「原合计行 11/11/6 与分类行加总不一致，")
print("      本版已按附表1修订为 12/15/10」——文档内部的总数自己加不起来，是常态，")
print("      不是个例。所以凡是拿来当验收口径的数，都要这样重算一遍。")

# ---------------------------------------------------------------- 2 点检五十六项
head("[2] 56 项能力点检：结论分布与缺口构成")
CONCL = {"满足": 21, "部分满足": 25, "不满足": 10}
print("结论分布 %s → 加总 %d，点检清单写 56 项 → %s"
      % (list(CONCL.values()), sum(CONCL.values()),
         "一致" if sum(CONCL.values()) == 56 else "不一致"))
print("满足率 = %d / %d = %.1f%%；含部分满足 = %d / %d = %.1f%%"
      % (21, 56, 21 / 56 * 100, 21 + 25, 56, 46 / 56 * 100))
GAP = {"运筹求解器（LP/MIP/启发式/增量/数值稳定性）": 5,
       "本体建模 + SHACL 校验 + 图谱推理": 3,
       "消息队列": 1, "DAG 分析组件": 1}
print("10 项不满足的构成 %s → 加总 %d → %s"
      % (list(GAP.values()), sum(GAP.values()),
         "一致" if sum(GAP.values()) == 10 else "不一致"))
print("  求解器一项占 %d/10 = %.0f%% 的硬缺口——这解释了为什么技术栈方案里"
      % (5, 5 / 10 * 100))
print("  COPT 是第一个被点名外挂的组件：智能体平台自带的算法节点不做 MIP。")

# ---------------------------------------------------------------- 3 规则与约束
head("[3] 68 条规则 / 137 条约束：结构对账")
print("规则：主线 10（R001~R010）+ 七大扰动 7×8=56（R011~R066）+ ECN 排查 2（R067~R068）")
print("      10 + %d + 2 = %d，清单实际行数 68 → %s" % (7 * 8, 10 + 56 + 2, "一致"))
print("约束：硬约束 HC-01~11 适用单元 67 + 软约束 SC-01~13 适用单元 70 = %d，" % (67 + 70))
print("      文档写 137 条 → %s（注意口径：137 数的是「适用单元」，不是约束模板条数 %d）"
      % ("一致" if 67 + 70 == 137 else "不一致", 11 + 13))
# 68 条规则的执行情况（逐条统计 xlsx「规则执行情况」列）
EXE = {"完全执行": 5, "部分执行": 51, "未执行": 12}
print("执行情况 %s → 加总 %d → %s"
      % (list(EXE.values()), sum(EXE.values()),
         "一致" if sum(EXE.values()) == 68 else "不一致"))
print("  完全执行占比 = %d / %d = %.1f%%；未执行 = %d / %d = %.1f%%"
      % (5, 68, 5 / 68 * 100, 12, 68, 12 / 68 * 100))
print("  确认状态倒是很好：完全确认 50 + 部分确认 18 = 68，未确认 0 条。")
print("  「业务把规则说清楚了」和「系统把规则跑起来了」是两个字段，")
print("  这两个字段的差（68 - 5 = 63 条没完全落地）就是智能体要填的坑。")

# ---------------------------------------------------------------- 4 数据规模
head("[4] 数据规模：四区间、交付口径、二期倍率")
STAGE = [("区间一 基础骨架", 9812, "25~30%"), ("区间二 核心参数", 26228, "40~45%"),
         ("区间三 完备增强", 46708, "50~55%"), ("区间四 核心全量", 68884, "≥60%")]
prev = 0
for name, cnt, acc in STAGE:
    print("  %-14s %6d 条  增量 %+6d  预估准确率 %s" % (name, cnt, cnt - prev, acc))
    prev = cnt
print("交付口径 68,884 / 核心专识口径 71,888 → 差 %d 条（%.1f%%），"
      % (71888 - 68884, (71888 - 68884) / 71888 * 100))
print("  差的这 3,004 条在两份文档里分别是「一期验收分母」和「建设总量」，")
print("  做进度看板前必须问清用哪个：差 4.2% 的分母，进度条会差 4.2 个百分点。")
print("二期全量 160,160 条 = 交付口径 %.2f 倍 = 核心专识口径 %.2f 倍"
      % (160160 / 68884, 160160 / 71888))
print("通识：设计 19,800 条 / 交付 54,400 条 → 交付是设计的 %.2f 倍（含 T1~T5+M 六集）"
      % (54400 / 19800))

# ---------------------------------------------------------------- 5 KPI 倍数
head("[5] K1~K6：客户明码标价的提升幅度，换算成倍数")
K = [
    ("K1 方案人工采纳率", "20~30%", "≥85%", lambda x: 85 / x, [20, 30], "百分点 +55~+65"),
    ("K2 夜间全量重排耗时", "12 h", "1~2 h", lambda x: 12 / x, [2, 1], "倍数取倒数"),
    ("K3 变更影响面评估", "2~3 h", "≤15 min", lambda x: x / 15, [120, 180], "分钟口径"),
    ("K5 装配齐套率", "60%", "100%", lambda x: 100 / x, [60], "硬约束化：不齐套不许开工"),
    ("K6 试车日计划达成率", "50%", "显著提升", None, [], "现场问卷给的是 95%"),
]
for name, now, tgt, f, xs, note in K:
    if f:
        vals = [f(v) for v in xs]
        print("  %-18s %-9s → %-7s  %.2f×（区间 %.2f~%.2f）｜%s"
              % (name, now, tgt, max(vals), min(vals), max(vals), note))
    else:
        print("  %-18s %-9s → %-7s  未量化｜%s" % (name, now, tgt, note))
print("  K3 是这里面最狠的一条：15 分钟不是「快一点」，是把变更评估从")
print("  「排进今天的会」变成「现在就能答」。现场的人工值是 2~3 小时起，")
print("  也就是 %.1f~%.1f 倍——这条 KPI 一旦没做到，前面的方案再好也接不住扰动。"
      % (120 / 15, 180 / 15))

# ---------------------------------------------------------------- 6 问卷与接口
head("[6] 调研与接口的规模（这些数决定了工作量估算）")
Q = [("业务问卷 B-01~B-38", 38), ("智能体专项问卷 A-01~A-30", 30), ("角色职责问卷 R-01~R-14", 14)]
print("  问卷项 %s → 共 %d 项（覆盖业务/数据/组织/系统四维、七道工序）"
      % ([q[1] for q in Q], sum(q[1] for q in Q)))
print("  系统接口：字段级取数 111 项 + 跨系统字段关联 20 类")
print("  MCP 工具 24 个，其中写工具 1 个（write_aps_plan）→ 写面占 %.1f%%" % (1 / 24 * 100))
print("  案例与经验：扰动案例 840 条 + 专家经验 600 条 + 规则 68 条 + 约束适用单元 137 条")

head("一句话：能加总的数字才叫口径，加不起来的叫故事。")
print("      上面 6 段全部能加总一致；唯一「印在文档里但自己承认加不起来」的")
print("      是 37 项贡献度三分的原合计行（11/11/6 ≠ 37），本版已修订为 12/15/10。")
print("      读别人的方案时，先做这一步，比读 PPT 快十倍。")
