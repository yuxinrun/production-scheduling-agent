def disp_w(s):
    # 等宽字体里 CJK／全角标点占 2 列，不这么算表格会歪
    from unicodedata import east_asian_width
    return sum(2 if east_asian_width(c) in "WF" else 1 for c in str(s))


def pad(s, n):
    s = str(s)
    return s + " " * max(0, n - disp_w(s))


def pct(n, d):
    return f"{n / d * 100:.2f}%" if d else "n/a"


