def codes_of_set(text):
    """编号 + 区间简写（『M-01~05』）展开后的集合"""
    out = set(codes_of(text))
    for m in RANGE.finditer(text or ""):
        out |= {f"{m.group(1)}-{i:02d}" for i in range(int(m.group(2)), int(m.group(3)) + 1)}
    return out


